// Bundles the Markdown parser into src/lib/richtext/vendor/markdown-tree.js.
// Run `pnpm vendor:markdown` after changing the parser packages or the entry.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

const root = fileURLToPath(new URL('..', import.meta.url));
const outDir = fileURLToPath(new URL('../src/lib/richtext/vendor', import.meta.url));
const versions = [
	'mdast-util-from-markdown',
	'micromark-extension-gfm-strikethrough',
	'mdast-util-gfm-strikethrough',
	'micromark-extension-gfm-table',
	'mdast-util-gfm-table',
	'micromark-extension-gfm-footnote',
	'mdast-util-gfm-footnote',
	'micromark-extension-gfm-task-list-item',
	'mdast-util-gfm-task-list-item',
	'micromark-extension-math',
	'mdast-util-math'
].map((name) => {
	const manifest = JSON.parse(readFileSync(`${root}node_modules/${name}/package.json`, 'utf8'));
	return `${name}@${manifest.version}`;
});

await build({
	configFile: false,
	root,
	logLevel: 'warn',
	// The packages' production builds, without their browser-only (DOM) variants, so the
	// result also runs in Workers and Node.
	resolve: { conditions: ['module', 'production'], mainFields: ['module', 'main'] },
	build: {
		lib: {
			entry: fileURLToPath(new URL('./markdown-tree-entry.js', import.meta.url)),
			formats: ['es'],
			fileName: () => 'markdown-tree.js'
		},
		outDir,
		emptyOutDir: false,
		minify: false,
		target: 'es2022',
		copyPublicDir: false
	}
});

const file = `${outDir}/markdown-tree.js`;
const banner = `// @ts-nocheck
// Generated by scripts/vendor-markdown.mjs; do not edit.
// Bundled, MIT-licensed: ${versions.join(', ')}
// and their dependencies (micromark, mdast-util-to-string, decode-named-character-reference,
// character-entities, unist-util-stringify-position and the micromark-* packages),
// (c) Titus Wormer and contributors. https://github.com/micromark/micromark
`;
writeFileSync(file, banner + readFileSync(file, 'utf8'));
